import { cleanup, fireEvent, render, screen } from '@testing-library/react';
import { afterEach, expect, it, vi } from 'vitest';
import { DashboardView } from '../src/components/DashboardView';
import { INITIAL_USERS } from '../src/data/initialData';
import { saleFixture } from './helpers/sale-fixtures';
import { formatPKR } from '../src/utils/formatCurrency';
afterEach(cleanup);
it('bounds 10,002 report rows while preserving full totals, pagination, filters and receipt selection', () => {
  const now = new Date().toISOString();
  const orders = Array.from({ length: 10002 }, (_, n) => ({ ...saleFixture(`report-${n}`), createdAt: now, persistenceState: 'saved' as const, orderNumber: `#REPORT-${n}`, paymentMethod: n === 10001 ? 'card' as const : 'cash' as const }));
  const select = vi.fn();
  const view = render(<DashboardView orders={orders} products={[]} currentUser={INITIAL_USERS[0]} onNavigateToTab={vi.fn()} onSelectOrderPreview={select} />);
  const rows = () => view.container.querySelectorAll('tbody tr');
  expect(rows()).toHaveLength(50);
  expect(screen.getByRole('status')).toHaveTextContent('Rows 1–50 of 10002');
  expect(screen.getByText(`Total: ${formatPKR(orders.reduce((sum, order) => sum + order.totalPaisa, 0))}`)).toBeInTheDocument();
  expect(screen.getByRole('button', { name: 'Previous page' })).toBeDisabled();
  fireEvent.click(screen.getByRole('button', { name: 'Next page' }));
  expect(rows()).toHaveLength(50); expect(screen.getByText('#REPORT-50')).toBeInTheDocument();
  fireEvent.click(screen.getAllByRole('button', { name: 'Reprint Slips' })[0]);
  expect(select).toHaveBeenLastCalledWith(orders[50]);
  fireEvent.click(screen.getByRole('button', { name: 'Last page' }));
  expect(rows()).toHaveLength(2); expect(screen.getByText('#REPORT-10001')).toBeInTheDocument();
  expect(screen.getByRole('button', { name: 'Next page' })).toBeDisabled();
  fireEvent.click(screen.getByRole('button', { name: 'Card Only' }));
  expect(rows()).toHaveLength(1); expect(screen.getByRole('status')).toHaveTextContent('Page 1 of 1');
  expect(screen.getByText(`Total: ${formatPKR(orders[10001].totalPaisa)}`)).toBeInTheDocument();
  fireEvent.click(screen.getByRole('button', { name: 'Yesterday' }));
  expect(rows()).toHaveLength(0); expect(screen.getByText(/No takeaway orders found/)).toBeInTheDocument();
});
